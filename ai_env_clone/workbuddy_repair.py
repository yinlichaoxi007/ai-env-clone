# 修复计划（dry-run）
# --------------------------------------------------------------------------- #
@dataclass
class WbRepairPlan:
    """一次「修复会话数据」的 dry-run 计划。"""

    home: str = ""
    db_path: str = ""
    fix_owner_ids: list = field(default_factory=list)
    register: list = field(default_factory=list)          # UnregisteredSession
    add_workspaces: list = field(default_factory=list)     # cwd 列表
    move_snapshots: list = field(default_factory=list)     # StaleSnapshot
    notes: list = field(default_factory=list)
    result: "WbCheckResult | None" = None

    @property
    def empty(self) -> bool:
        return not (self.fix_owner_ids or self.register or self.add_workspaces
                    or self.move_snapshots)

    def total(self) -> int:
        return (len(self.fix_owner_ids) + len(self.register)
                + len(self.add_workspaces) + len(self.move_snapshots))

    def describe(self) -> list:
        lines: list = []
        if self.fix_owner_ids:
            lines.append("① 把 %d 条导入会话的 user_id 改为空串（当前账号即可见）："
                         % len(self.fix_owner_ids))
            lines.extend("   - %s" % r.label() for r in (self.result.wrong_owner if self.result else []))
        if self.register:
            lines.append("② 补登记 %d 个「磁盘有正文、库里没登记」的会话：" % len(self.register))
            lines.extend("   - %s → 工作区 %s" % (u.label(), u.cwd) for u in self.register)
        if self.add_workspaces:
            lines.append("③ 补登记 %d 个缺失的工作区行：" % len(self.add_workspaces))
            lines.extend("   - %s" % p for p in self.add_workspaces)
        if self.move_snapshots:
            lines.append("④ 移走 %d 个陈旧的侧栏快照（备份为 <文件>.bak.<时间戳>）："
                         % len(self.move_snapshots))
            lines.extend("   - %s：%s" % (s.path, s.reason) for s in self.move_snapshots)
        lines.extend(self.notes)
        return lines


def plan_wb_repair(wb_home: "str | None" = None) -> WbRepairPlan:
    """生成 dry-run 修复计划（不写盘）。"""
    res = detect_wb_sessions(wb_home)
    plan = WbRepairPlan(home=res.home, db_path=res.db_path, result=res)
    plan.fix_owner_ids = [r.session_id for r in res.wrong_owner]
    plan.register = list(res.unregistered)
    plan.add_workspaces = list(res.missing_workspaces)
    plan.move_snapshots = list(res.stale_snapshot)
    if res.orphan_rows:
        plan.notes.append("注：%d 条会话正文缺失（磁盘没有 .jsonl），无法自动补，"
                          "本次不处理。" % len(res.orphan_rows))
    if res.foreign_owner:
        plan.notes.append("注：%d 条会话不属于当前账号且非本工具导入，保持原样。"
                          % len(res.foreign_owner))
    if not res.db_exists:
        plan.notes.append("注：未找到 %s，无法写库；请先启动一次 WorkBuddy 再修复。"
                          % res.db_path)
    return plan


