#: 侧栏「秒开」磁盘快照文件名（``<数据根>/<uid>/`` 下，按 uid 分片防切账号串号）。
SNAPSHOT_NAME = "sidebar-list-snapshot.json"

#: 导入行的归属约定值（见模块 docstring：产品谓词是 ``user_id = uid or user_id = ''``）。
IMPORT_USER_ID = ""

#: 与 WorkBuddy 产品源码一致的 uuid 形态（uid 目录 / 会话 id 判定用）。
_UUID_RE = re.compile(
    r"^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$"
)

#: 划词临时会话的 sidecar 标记：产品重建索引时据此**跳过**（否则临时会话会涌进列表）。
_QUICKASK_SUFFIX = ".quickask"


def resolve_wb_home(wb_home: str | None = None) -> str:
    """WorkBuddy 用户数据根 ``~/.workbuddy``（可由调用方显式传入，便于测试）。"""
    if wb_home:
        return wb_home
    from .adapters.workbuddy import _workbuddy_home

    return _workbuddy_home()


def _stamp() -> str:
    """备份名用的 UTC 时间戳（冒号/点换掉，避免 Windows 文件名歧义）。"""
    return datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")


def normalize_workspace_path(path: str) -> str:
    """工作区路径归一（与产品 ``normalizeTaskWorkspacePath`` 同规则）。

    ``\\`` -> ``/``、去尾分隔符、盘符形态（``d:/...``）整体小写。用于比对
    ``workspaces.path``，防止 ``D:\\a`` 与 ``d:/a`` 被当成两个工作区而重复插行。
    """
    p = (path or "").strip().replace("\\", "/").rstrip("/")
    if re.match(r"^[a-zA-Z]:/", p):
        p = p.lower()
    return p


def is_auto_generated_workspace(cwd: str) -> bool:
    """cwd 是否是 WorkBuddy 为 playground 现造的时间戳目录（``2026-10-05-21-38-00``）。

    产品据此把会话标成 ``space.autoGenerated``，这类会话**不按工作区分组**，
    所以不该为它补 ``workspaces`` 行。
    """
    base = (cwd or "").replace("\\", "/").rstrip("/").split("/")[-1] if cwd else ""
    return bool(re.match(r"^\d{4}-\d{2}-\d{2}-\d{2}-\d{2}-\d{2}$", base or ""))


