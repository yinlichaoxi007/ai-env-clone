# 当前登录 uid 的发现（仅用于报告与定位快照文件；写入值恒为空串）
# --------------------------------------------------------------------------- #
def detect_current_uid(wb_home: str) -> "tuple[str, str]":
    """尽力发现 WorkBuddy 当前登录 uid。

    三个来源都是产品自己按 uid 落盘的位置，取**最近活动**的那个：
    ``<uid>/sidebar-list-snapshot.json``、``storage/user-<uid>[-personal]/``、
    ``memory/<uid>_memory.md``。

    :return: ``(uid, 来源说明)``；发现不了返回 ``("", 说明)``（按未登录处理）。
    """
    cands: list = []

    def _add(uid: str, path: str, note: str) -> None:
        try:
            mtime = os.stat(_longpath(path)).st_mtime
        except OSError:
            mtime = 0.0
        cands.append((mtime, uid, note))

    try:
        names = os.listdir(_longpath(wb_home))
    except OSError:
        names = []
    for name in names:
        if not _UUID_RE.match(name):
            continue
        snap = os.path.join(wb_home, name, SNAPSHOT_NAME)
        if os.path.isfile(_longpath(snap)):
            _add(name, snap, "侧栏快照目录")
        elif os.path.isdir(_longpath(os.path.join(wb_home, name))):
            _add(name, os.path.join(wb_home, name), "uid 数据目录")

    storage = os.path.join(wb_home, "storage")
    if os.path.isdir(_longpath(storage)):
        for name in os.listdir(_longpath(storage)):
            if not name.startswith("user-"):
                continue
            uid = re.sub(r"-personal$", "", name[len("user-"):])
            if _UUID_RE.match(uid):
                _add(uid, os.path.join(storage, name), "用户级存储")

    memory = os.path.join(wb_home, "memory")
    if os.path.isdir(_longpath(memory)):
        for name in os.listdir(_longpath(memory)):
            if not name.endswith("_memory.md"):
                continue
            uid = name[: -len("_memory.md")]
            if _UUID_RE.match(uid):
                _add(uid, os.path.join(memory, name), "用户级记忆")

    if not cands:
        return "", "未在数据根里发现任何 uid 痕迹（按未登录处理）"
    cands.sort(key=lambda c: c[0], reverse=True)
    mtime, uid, note = cands[0]
    extra = ""
    if len(cands) > 1:
        others = {c[1] for c in cands[1:]}
        if others:
            extra = "；另有 %d 个历史 uid 痕迹（取最近活动的）" % len(others)
    return uid, "来源：%s%s" % (note, extra)


