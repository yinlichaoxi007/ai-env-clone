def scan_projects(projects_dir: str) -> "dict[str, dict]":
    """列出 ``projects/<工作区编码>/<会话 id>.jsonl``，返回 ``{sid: {"path","slug"}}``。"""
    out: dict = {}
    if not os.path.isdir(_longpath(projects_dir)):
        return out
    for slug in sorted(os.listdir(_longpath(projects_dir))):
        sdir = os.path.join(projects_dir, slug)
        if not os.path.isdir(_longpath(sdir)):
            continue
        for fn in sorted(os.listdir(_longpath(sdir))):
            if not fn.endswith(".jsonl"):
                continue
            sid = fn[: -len(".jsonl")]
            if sid:
                out[sid] = {"path": os.path.join(sdir, fn), "slug": slug}
    return out


def _content_text(event: dict) -> str:
    """从一条 ``message`` 事件里取纯文本（content 块形态多样，尽力而为）。"""
    content = event.get("content")
    parts: list = []
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        for block in content:
            if isinstance(block, dict):
                for key in ("text", "input_text", "output_text"):
                    val = block.get(key)
                    if isinstance(val, str) and val:
                        parts.append(val)
                        break
    return "\n".join(parts)


def extract_session_info(jsonl_path: str) -> dict:
    """从事件流提取 ``cwd`` / 标题 / 起止时间（与产品重建索引同口径：正推 jsonl）。

    标题优先 ``ai-title`` 事件的 ``aiTitle``，退化到首条用户消息（截 60 字）；
    时间取事件 ``timestamp`` 的最小/最大值，没有则用文件 mtime/btime 兜底。
    """
    cwd = ""
    ai_title = ""
    first_user = ""
    first_ms = 0
    last_ms = 0
    try:
        with open(_longpath(jsonl_path), "r", encoding="utf-8", errors="replace") as fh:
            for line in fh:
                line = line.strip()
                if not line:
                    continue
                try:
                    ev = json.loads(line)
                except ValueError:
                    continue
                if not isinstance(ev, dict):
                    continue
                ms = ev.get("timestamp")
                if isinstance(ms, (int, float)) and ms:
                    first_ms = min(first_ms, int(ms)) if first_ms else int(ms)
                    last_ms = max(last_ms, int(ms))
                if not cwd and isinstance(ev.get("cwd"), str) and ev["cwd"]:
                    cwd = ev["cwd"]
                etype = ev.get("type")
                if etype == "ai-title" and isinstance(ev.get("aiTitle"), str):
                    if ev["aiTitle"].strip():
                        ai_title = ev["aiTitle"].strip()
                elif etype == "message" and ev.get("role") == "user" and not first_user:
                    first_user = _content_text(ev).strip()
    except OSError:
        pass
    title = ai_title or (first_user[:60] if first_user else "")
    try:
        st = os.stat(_longpath(jsonl_path))
        if not last_ms:
            last_ms = int(st.st_mtime * 1000)
        if not first_ms:
            first_ms = int(getattr(st, "st_birthtime", st.st_mtime) * 1000)
    except OSError:
        pass
    return {"cwd": cwd, "title": title, "created_ms": first_ms, "updated_ms": last_ms}


# --------------------------------------------------------------------------- #
# 库内行读取
# --------------------------------------------------------------------------- #
#: 关注的列，按 ``pragma table_info`` 现取。``transport`` / ``deleted_at`` /
#: ``source_mode`` 都是后续迁移才加的，旧构建的库里没有；写死列名会让整条
#: select 失败并被当成「一个会话都没有」，把真问题伪装成空结果。
_SESSION_COLUMNS = (
    "id", "cwd", "user_id", "title", "status", "created_at", "updated_at",
    "deleted_at", "is_playground", "source_mode", "transport",
)


def read_sessions(db_path: str) -> list[dict]:
    """读 ``sessions`` 表；库/表不存在时返回空列表（``db_exists`` 由调用方标注）。"""
    if not os.path.isfile(_longpath(db_path)):
        return []
    try:
        con = _open_sqlite_ro(db_path)
    except sqlite3.Error:
        return []
    try:
        have = {r[1] for r in con.execute("pragma table_info(sessions)")}
        cols = [c for c in _SESSION_COLUMNS if c in have]
        if "id" not in cols:
            return []
        return [dict(zip(cols, row)) for row in
                con.execute("select %s from sessions" % ", ".join(cols))]
    except sqlite3.Error:
        return []
    finally:
        con.close()


def read_workspace_paths(db_path: str) -> list[str]:
    """读 ``workspaces.path`` 全量；失败返回空列表。"""
    if not os.path.isfile(_longpath(db_path)):
        return []
    try:
        con = _open_sqlite_ro(db_path)
    except sqlite3.Error:
        return []
    try:
        return [r[0] for r in con.execute("select path from workspaces") if r and r[0]]
    except sqlite3.Error:
        return []
    finally:
        con.close()


def workspace_table_exists(db_path: str) -> bool:
    """``workspaces`` 表是否存在且可读。库都不存在时返回 False（调用方另有说明）。"""
    if not os.path.isfile(_longpath(db_path)):
        return False
    try:
        con = _open_sqlite_ro(db_path)
    except sqlite3.Error:
        return False
    try:
        return bool(con.execute(
            "select 1 from sqlite_master where type='table' and name='workspaces'").fetchone())
    except sqlite3.Error:
        return False
    finally:
        con.close()


