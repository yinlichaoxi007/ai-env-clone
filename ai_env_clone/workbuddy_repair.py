"""WorkBuddy 会话索引体检与修复（与 :mod:`ai_env_clone.dsh_repair` 同构：
检测 → dry-run 计划 → 备份写盘 → 复检）。

为什么需要这个模块（2026-10-05 实测根因）
----------------------------------------
把 DSH 等其他工具的会话导入 WorkBuddy 后，「选择工作区」里看得到导入的工作区，
会话列表却一条都没有。原因是 WorkBuddy 侧栏**本地**会话列表的谓词（从其
``app.asar`` 的 ``LocalConversationsImpl.visibleRows`` 核对）是::

    where transport = 'local' and deleted_at is null
      and (user_id = <当前登录 uid> or user_id = '')

而 ``workspaces`` 表只有 ``path`` + ``last_opened_at``、**没有 user 维度**。
旧导入实现给 ``sessions.user_id`` 写了一个凭空发明的 ``imported`` ⇒ 工作区照常显示、
会话全被过滤掉，症状正好是「有工作区、没会话」。

``user_id = ''`` 是 WorkBuddy 自己给「无主/导入行」的约定：它「从 ``projects/``
重建 session 索引」时也把 userId 置空串，注释写明这样"对当前用户可见"。故本模块
（以及 ``SessionWriter.write_workbuddy``）**一律写空串**，不猜 uid、不借别的行的 uid
（借会把第一条错误值一路继承下去）。

检测覆盖的失配（前四类可自动修，后两类只报不改）
------------------------------------------------
1. 归属不对：``transport='local'`` 且 ``user_id`` 既非当前 uid 也非空串的**本工具导入行**
   （``source_mode='import'``）⇒ 置为空串。
2. 未登记：``projects/<工作区编码>/<会话 id>.jsonl`` 在磁盘上、库里没有对应行
   （导入时库被占用 / 缺库导致只剩正文）⇒ 按事件流补登记。
3. 工作区缺行：会话的 ``cwd`` 在 ``workspaces`` 表里没有记录 ⇒ 补登记。
4. 侧栏快照陈旧：``<数据根>/<uid>/sidebar-list-snapshot.json``（冷启动首帧打底用的
   磁盘快照）里的会话集合与库内可见集合不一致（典型为导入后留下的**空快照**）
   ⇒ 移走该文件（``version`` 不符或读不到时产品本来就当 miss 处理，移走无害）。
5. 正文缺失：库里有行、磁盘没有 ``<id>.jsonl`` —— 内容无法凭空重建，只报告。
6. 别人的账号：非本工具导入、又不属于当前 uid 的本地行 —— 可能是其他账号的数据，
   只报告不动。

安全边界：只碰 ``transport='local'`` 且未软删的行；**云端行**（``transport='cloud'``
以 ``user_id`` 为对账主键）一律不碰；写盘前先备份 ``workbuddy.db``（含 ``-wal``/``-shm``）；
用 ``begin immediate`` 拿写锁，拿不到（WorkBuddy 正在运行）就整体不写、如实报错。
"""

