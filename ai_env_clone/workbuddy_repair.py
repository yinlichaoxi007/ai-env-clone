_INSERT_SESSION = (
    "insert or ignore into sessions(id, cwd, user_id, title, status, created_at,"
    " updated_at, last_activity_at, is_playground, source_mode, mode)"
    " values(?,?,?,?,?,?,?,?,?,?,?)"
)
_UPSERT_WORKSPACE = (
    "insert into workspaces(path, last_opened_at) values(?,?)"
    " on conflict(path) do update set last_opened_at=max(last_opened_at, excluded.last_opened_at)"
)


def _backup_file(path: str) -> str:
    """就地复制一份 ``<文件>.bak.<UTC>``；失败返回空串。"""
    dst = "%s.bak.%s" % (path, _stamp())
    try:
        shutil.copyfile(_longpath(path), _longpath(dst))
    except OSError:
        return ""
    return dst


def apply_wb_repair(wb_home: "str | None", plan: "WbRepairPlan | None" = None,
                    backup: bool = True) -> dict:
    """执行修复：备份库 → 改归属 → 补登记 → 补工作区 → 移走陈旧快照。

    :return: ``{"ok","error","backups","ownership","registered","workspaces",
        "snapshots_moved"}``；任何一步失败都不提交事务（快照移动只在库提交后进行）。
    """
    home = resolve_wb_home(wb_home or "")
    plan = plan or plan_wb_repair(home)
    outcome: dict = {
        "ok": False, "error": "", "backups": [], "ownership": 0,
        "registered": [], "workspaces": [], "snapshots_moved": [],
    }
    if plan.empty:
        outcome["ok"] = True
        return outcome
    db = plan.db_path or os.path.join(home, "workbuddy.db")
    if not os.path.isfile(_longpath(db)):
        outcome["error"] = "未找到会话索引库 %s：请先启动一次 WorkBuddy 生成库，再点修复。" % db
        return outcome

    if backup:
        for extra in ("", "-wal", "-shm"):
            src = db + extra
            if os.path.isfile(_longpath(src)):
                bak = _backup_file(src)
                if bak:
                    outcome["backups"].append(bak)

    con: "sqlite3.Connection | None" = None
    try:
        con = _open_sqlite_rw(db)
        # begin immediate：拿不到写锁说明 WorkBuddy（或其它进程）正在写，
        # 此时改动会被覆盖或写坏体验，直接拒绝，别留下「修了但没生效」的现场。
        con.execute("begin immediate")
    except sqlite3.Error as exc:
        if con is not None:
            con.close()
        outcome["error"] = (
            "无法取得 workbuddy.db 写锁（%s）：请先完全退出 WorkBuddy（含系统托盘图标）"
            "再点修复。" % exc)
        return outcome

    try:
        if plan.fix_owner_ids:
            marks = ",".join("?" * len(plan.fix_owner_ids))
            con.execute("update sessions set user_id = '' where id in (%s)" % marks,
                        plan.fix_owner_ids)
            outcome["ownership"] = len(plan.fix_owner_ids)
        now = int(datetime.now(timezone.utc).timestamp() * 1000)
        for un in plan.register:
            con.execute(_INSERT_SESSION, (
                un.session_id, un.cwd, IMPORT_USER_ID, un.title, "completed",
                un.created_ms or now, un.updated_ms or now, un.updated_ms or now,
                0, "import", "craft"))
            outcome["registered"].append(un.session_id)
        for cwd in plan.add_workspaces:
            con.execute(_UPSERT_WORKSPACE, (cwd, now))
            outcome["workspaces"].append(cwd)
        con.commit()
    except sqlite3.Error as exc:
        try:
            con.rollback()
        except sqlite3.Error:
            pass
        outcome["error"] = "写入会话索引库失败：%s（库未改动，事件流仍在原位）" % exc
        return outcome
    finally:
        con.close()

    for stale in plan.move_snapshots:
        if not os.path.isfile(_longpath(stale.path)):
            continue
        dst = _backup_file(stale.path)
        if not dst:
            # 备份没成就别移走原文件：宁可留一个陈旧快照（产品会当 miss 或被下次
            # prefetch 覆盖），也不能把用户的唯一线索弄丢。
            outcome.setdefault("snapshot_errors", []).append(
                "%s：备份失败，未移走" % stale.path)
            continue
        try:
            os.replace(_longpath(stale.path), _longpath(dst))
            outcome["snapshots_moved"].append(stale.path)
        except OSError:
            outcome.setdefault("snapshot_errors", []).append(
                "%s：移走失败，请手动删除该文件" % stale.path)

    outcome["ok"] = True
    return outcome
